const DICTS: Record<Lang, Dict> = { cs, en, de, es };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
  return s;
}

/** Hook: vrací funkci t(key, vars?) + aktuální jazyk. Reaguje na změnu v Nastavení. */
export function useT() {
  const { state } = useApp();
  const lang = state.settings.lang ?? 'en';
  const t = (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { t, lang };
}

/** Instrukce pro AI, aby odpovídala ve zvoleném jazyce (přidává se do system promptu). */
export function aiLangInstruction(lang: Lang): string {
  if (lang === 'cs') return '\n\nDŮLEŽITÉ: Odpovídej v ČEŠTINĚ.';
  if (lang === 'de') return '\n\nWICHTIG: Antworte auf DEUTSCH.';
  if (lang === 'es') return '\n\nIMPORTANTE: Responde en ESPAÑOL.';
  return '\n\nIMPORTANT: Reply in ENGLISH.';
}
